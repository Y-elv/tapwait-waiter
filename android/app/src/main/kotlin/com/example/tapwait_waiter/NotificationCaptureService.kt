
package com.example.tapwait_waiter

import android.app.Notification
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import android.util.Log
import org.json.JSONObject
import java.io.BufferedReader
import java.io.InputStreamReader
import java.net.HttpURLConnection
import java.net.URL
import java.time.Instant
import java.util.concurrent.Executors

class NotificationCaptureService : NotificationListenerService() {

    private val executor = Executors.newSingleThreadExecutor()

    override fun onListenerConnected() {
        super.onListenerConnected()
        Log.d(TAG, "Notification listener connected")
    }

    override fun onListenerDisconnected() {
        super.onListenerDisconnected()
        Log.w(TAG, "Notification listener disconnected")
    }

    override fun onNotificationPosted(sbn: StatusBarNotification) {
        super.onNotificationPosted(sbn)

        // Avoid uploading notifications generated by Tapwait itself.
        if (sbn.packageName == packageName) return

        val notification = sbn.notification
        val extras = notification.extras

        val packageName = sbn.packageName

        val title = extras
            ?.getCharSequence(Notification.EXTRA_TITLE)
            ?.toString()
            ?.trim()
            .orEmpty()

        val content = (
            extras?.getCharSequence(Notification.EXTRA_BIG_TEXT)
                ?: extras?.getCharSequence(Notification.EXTRA_TEXT)
                ?: extras?.getCharSequence(Notification.EXTRA_SUB_TEXT)
                ?: extras?.getCharSequence(Notification.EXTRA_TITLE_BIG)
            )
            ?.toString()
            ?.trim()
            .orEmpty()

        val sourceApp = try {
            val appInfo = packageManager.getApplicationInfo(packageName, 0)
            packageManager.getApplicationLabel(appInfo).toString()
        } catch (e: Exception) {
            packageName
        }

        val postedAt = Instant.ofEpochMilli(sbn.postTime).toString()

        // StatusBarNotification.key identifies this Android notification.
        val notificationKey = sbn.key

        Log.d(
            TAG,
            "Notification detected: app=$packageName, " +
                "hasTitle=${title.isNotBlank()}, " +
                "hasContent=${content.isNotBlank()}, postedAt=$postedAt"
        )

        executor.execute {
            uploadNotification(
                sourceApp = sourceApp,
                packageName = packageName,
                title = title,
                content = content,
                notificationKey = notificationKey,
                postedAt = postedAt
            )
        }
    }

    private fun uploadNotification(
        sourceApp: String,
        packageName: String,
        title: String,
        content: String,
        notificationKey: String,
        postedAt: String
    ) {
        var connection: HttpURLConnection? = null

        try {
            val url = URL(API_URL)
            connection = (url.openConnection() as HttpURLConnection).apply {
                requestMethod = "POST"
                connectTimeout = 15000
                readTimeout = 15000
                doOutput = true
                setRequestProperty("Accept", "*/*")
                setRequestProperty("Content-Type", "application/json; charset=UTF-8")
            }

            val payload = JSONObject().apply {
                put("deviceId", DEVICE_ID)
                put("deviceName", DEVICE_NAME)
                put("sourceApp", sourceApp)
                put("packageName", packageName)
                put("title", title.ifBlank { "Notification" })
                put(
                    "content",
                    content.ifBlank { "Notification preview unavailable" }
                )
                put("notificationKey", notificationKey)
                put("postedAt", postedAt)
            }

            connection.outputStream.use { output ->
                output.write(payload.toString().toByteArray(Charsets.UTF_8))
            }

            val statusCode = connection.responseCode
            val responseStream = if (statusCode in 200..299) {
                connection.inputStream
            } else {
                connection.errorStream
            }

            val responseBody = responseStream?.bufferedReader()?.use {
                it.readText()
            }.orEmpty()

            if (statusCode in 200..299) {
                Log.d(
                    TAG,
                    "Notification uploaded successfully: HTTP $statusCode"
                )
            } else {
                Log.e(
                    TAG,
                    "Notification upload failed: HTTP $statusCode, response=$responseBody"
                )
            }
        } catch (e: Exception) {
            Log.e(TAG, "Notification upload error: ${e.message}", e)
        } finally {
            connection?.disconnect()
        }
    }

    override fun onDestroy() {
        executor.shutdown()
        super.onDestroy()
    }

    companion object {
        private const val TAG = "TapwaitNotification"

        private const val API_URL =
            "https://tapwait-waiter-api.onrender.com/api/device-notifications"

        // Replace these with the actual registered device details.
        private const val DEVICE_ID = "6acf976ee09be9197924728e"
        private const val DEVICE_NAME = "Waiter Phone 1"
    }
}
